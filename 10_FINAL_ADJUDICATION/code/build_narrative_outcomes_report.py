"""Write 15_NARRATIVE_OUTCOMES/NARRATIVE_OUTCOMES_REPORT.md from the three structured tables (nothing is typed by hand).

The report lists every row as extracted (report, comparison, arm values, reported P, direction as reported) and counts
reports per domain or category. It does not pool, does not tally significance across reports, and does not turn an
unreported harm into a zero. Run after code/verify_narrative_outcomes.py passes.
"""
import csv, pathlib
from collections import Counter, defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[2]; OUT = ROOT / '10_FINAL_ADJUDICATION/15_NARRATIVE_OUTCOMES'
rows = lambda n: list(csv.DictReader(open(OUT / n, encoding='utf-8')))
cell = lambda s: str(s).replace('|', '/').replace('\n', ' ')
def table(head, body):
    return '\n'.join(['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(cell(c) for c in r) + ' |' for r in body])
arm = lambda v, n: f"{v} (n={n})" if n not in ('', 'not stated') else v

M, H, S = rows('recovery_milestones.csv'), rows('harms_structured.csv'), rows('satisfaction_acceptability.csv')
harm_rows = [r for r in H if r['reporting'] != 'Not located (not a zero)']
pending = sum(r['second_review'] == 'pending' for r in M + H + S)
L = ['# Narrative outcomes: recovery milestones, harms, satisfaction and acceptability', '',
     'Generated by `10_FINAL_ADJUDICATION/code/build_narrative_outcomes_report.py` from the structured tables in this folder, which '
     '`code/verify_narrative_outcomes.py` checks (verbatim quote on the stated PDF page, registry source hash, closed vocabularies).', '',
     '**Status.** Every value was extracted by a single extractor on 28 September 2026 with a page-located verbatim quotation. '
     f'{pending} rows are awaiting second review (`02_DECISIONS/v38/second_review_worksheet.csv`). No row has been second-reviewed.', '',
     '**How to read these tables.** They are descriptive. Length of stay, functional recovery, time to mobilisation, patient satisfaction '
     'and adverse events are registered additional outcomes (PROSPERO CRD420261452908), and the registered plan allows random-effects pooling '
     'when at least two comparable studies exist in a modality–comparator stratum. The review defined no quantitative estimand for them, and '
     'definitions, units, reporting formats (means, medians, categories, graphs), windows, care pathways (ERAS or not) and ascertainment differ '
     'between reports, so nothing is pooled here. Not pooling them is a disclosed deviation from the registered synthesis plan. Significance '
     'is not tallied across reports. The direction column repeats what each report found for its own comparison. Multi-arm trials appear once per '
     'comparison, with the shared control repeated; do not add them up. Missing reporting is not a zero.', '',
     '## Contents', '',
     f"- Recovery milestones: {len(M)} rows from {len({r['report_id'] for r in M})} reports",
     f"- Harms: {len(harm_rows)} rows from {len({r['report_id'] for r in harm_rows})} reports; {len(H) - len(harm_rows)} reports with no intervention-harm result located",
     f"- Satisfaction, acceptability and quality of life: {len(S)} rows from {len({r['report_id'] for r in S})} reports", '']

L += ['## 1. Recovery milestones', '']
by = defaultdict(list)
for r in M: by[r['domain']].append(r)
L += [table(['Domain', 'Reports', 'Rows', 'Linked to the canonical register'],
            [[d, len({r['report_id'] for r in rs}), len(rs), sum(bool(r['register_result_id']) for r in rs)] for d, rs in by.items()]), '']
for d, rs in by.items():
    L += [f'### {d}', '', table(['Report', 'Comparison', 'Outcome', 'Intervention', 'Control', 'Unit', 'Reported P', 'Direction as reported', 'Source'],
          [[r['report_id'], r['comparison'], r['outcome'] + f" ({r['statistic']})", arm(r['value_i'], r['n_i']), arm(r['value_c'], r['n_c']), r['unit'], r['reported_p'], r['direction'],
            f"p.{r['page']}" + (f", {r['register_result_id']} ({r['register_decision']})" if r['register_result_id'] else '')] for r in rs]), '']
    notes = [f"- {r['report_id']}, {r['outcome']}: {r['note']}" for r in rs if r['note']]
    if notes: L += ['Notes:', ''] + list(dict.fromkeys(notes)) + ['']

L += ['## 2. Harms', '', 'Categories are kept separate. Attribution is as the report states it. "Explicit zero" means the report says no such event '
      'occurred in that window; it is not proof that none could occur. No counts are pooled or summed across reports or categories.', '']
cats = Counter(r['category'] for r in harm_rows); reps = defaultdict(set)
for r in harm_rows: reps[r['category']].add(r['report_id'])
L += [table(['Category', 'Reports', 'Rows'], [[c, len(reps[c]), n] for c, n in cats.items()]), '']
for c in cats:
    rs = [r for r in harm_rows if r['category'] == c]
    L += [f'### {c}', '', table(['Report', 'Event', 'Attribution', 'Reporting', 'Intervention', 'Control', 'Window', 'Source'],
          [[r['report_id'], r['event'], r['attribution'], r['reporting'], f"{r['arm_i']}: {r['events_i']}/{r['n_i']}", f"{r['arm_c']}: {r['events_c']}/{r['n_c']}", r['window'], f"p.{r['page']}"] for r in rs]), '']
    notes = [f"- {r['report_id']}: {r['note']}" for r in rs if r['note']]
    if notes: L += ['Notes:', ''] + list(dict.fromkeys(notes)) + ['']
none = [r['report_id'] for r in H if r['reporting'] == 'Not located (not a zero)']
L += [f'### No intervention-harm result located ({len(none)} reports)', '', ', '.join(none) + '.', '',
      'For these reports the outcome-coverage audit found no explicit intervention-harm statement in the available text. This is not a report of zero events.', '']

L += ['## 3. Satisfaction, acceptability and quality of life', '', 'Instruments, scales, thresholds and time points differ; each is kept as reported and nothing is pooled or converted.', '']
for c in dict.fromkeys(r['construct'] for r in S):
    rs = [r for r in S if r['construct'] == c]
    L += [f'### {c}', '', table(['Report', 'Instrument', 'Time point', 'Comparison', 'Intervention', 'Control', 'Reported P', 'Use', 'Source'],
          [[r['report_id'], r['instrument'], r['time_point'], r['comparison'], arm(r['value_i'], r['n_i']), arm(r['value_c'], r['n_c']), r['reported_p'], r['synthesis'], f"p.{r['page']}"] for r in rs]), '']
    notes = [f"- {r['report_id']}: {r['note']}" for r in rs if r['note']]
    if notes: L += ['Notes:', ''] + list(dict.fromkeys(notes)) + ['']

(OUT / 'NARRATIVE_OUTCOMES_REPORT.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('NARRATIVE_OUTCOMES_REPORT.md:', len(M), 'milestone rows,', len(harm_rows), 'harms rows,', len(S), 'satisfaction rows')
